"""Install the skills, agents and MCP server for an agent client. The source of truth is this repository's plain
Markdown (``skills/``, ``agents/``, ``references/``); every client gets generated copies, never hand-edited ones.

    ros install --client claude    .claude/skills/<skill>/, .claude/agents/<agent>.md, .mcp.json
    ros install --client codex     .agents/skills/<skill>/, AGENTS.md (managed block), .codex/config.toml
    ros install --client gemini    GEMINI.md (managed block), .gemini/settings.json
    ros install --client agents    AGENTS.md (managed block) for any agent that reads it

The target is a project folder (default: the working directory) or, with ``--user``, the home folder. Each written
file's hash is kept in ``.research-os-install.json`` there; a file changed by hand since it was installed is refused
(listed, not overwritten) unless ``--force``. Config files that other tools share (``.mcp.json``, ``settings.json``,
``config.toml``, ``AGENTS.md``) are merged: only our entry or our marked block changes.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import sys

REPO = Path(__file__).resolve().parents[1]
CLIENTS = ("claude", "codex", "gemini", "agents")
MANIFEST = ".research-os-install.json"
BEGIN, END = "<!-- research-os:begin (generated by ros install; edit outside this block) -->", "<!-- research-os:end -->"
TOML_BEGIN, TOML_END = "# research-os:begin (generated by ros install)", "# research-os:end"


def server_entry() -> dict:
    """How a client starts the MCP server: this Python, this repository on the path. Works without pip install."""
    return {"command": sys.executable, "args": ["-m", "ros", "mcp"], "env": {"PYTHONPATH": str(REPO)}}


def skill_files() -> dict[str, bytes]:
    """Every skill folder with the shared references bundled under ``references/``, as relative path -> content."""
    refs = {f"references/{p.name}": p.read_bytes() for p in sorted((REPO / "references").glob("*.md"))}
    out = {}
    for d in sorted(p for p in (REPO / "skills").iterdir() if (p / "SKILL.md").exists()):
        for f in sorted(d.rglob("*")):
            if f.is_file():
                out[f"{d.name}/{f.relative_to(d).as_posix()}"] = f.read_bytes()
        out.update({f"{d.name}/{k}": v for k, v in refs.items()})
    return out


def agent_files() -> dict[str, bytes]:
    return {p.name: p.read_bytes() for p in sorted((REPO / "agents").glob("*.md"))}


def instructions() -> str:
    """The managed block for AGENTS.md / GEMINI.md: what Research OS is and how to use it from any agent."""
    skills = []
    for d in sorted((REPO / "skills").iterdir()):
        meta = _front(d / "SKILL.md")
        if meta:
            skills.append(f"- **{meta.get('name', d.name)}** (`{(REPO / 'skills' / d.name / 'SKILL.md').as_posix()}`): "
                          f"{meta.get('description', '')}")
    agents = []
    for p in sorted((REPO / "agents").glob("*.md")):
        meta = _front(p)
        agents.append(f"- **{meta.get('name', p.stem)}** (`{p.as_posix()}`): {meta.get('description', '')}")
    return "\n".join([
        BEGIN, "## Research OS", "",
        "The researcher's courses and projects live in Research OS records. Use the `ros` tools: over MCP (server "
        "`research-os`) or the shell (`python -m ros <tool> --json ...`, with this repository on PYTHONPATH: "
        f"`{REPO.as_posix()}`). `ros tools` lists them. Call `brief` first; when the researcher says what they want to learn or find "
        "out, call `engage` with their words, then loop `work`.", "",
        "Read the skill that fits the task before acting:", "", *skills, "",
        "Roles to give to a separate, fresh agent when the skill asks for one:", "", *agents, "",
        "Approving plans, deciding on claims and waiving ownership are the researcher's own acts; never do them for "
        "them. Rules: " + (REPO / "references" / "SAFETY.md").as_posix(), END])


# ---- writing ------------------------------------------------------------------------------------------------------
class Plan:
    """What an install would write, checked against the manifest before anything is touched."""

    def __init__(self, base: Path, force: bool):
        self.base, self.force = base, force
        self.writes: dict[Path, bytes] = {}
        self.manifest = _load_json(base / MANIFEST).get("files", {}) if (base / MANIFEST).exists() else {}

    def file(self, rel: str, data: bytes) -> None:
        self.writes[self.base / rel] = data

    def merged(self, rel: str, merge) -> None:
        path = self.base / rel
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        self.writes[path] = merge(old).encode("utf-8")

    def conflicts(self) -> list[str]:
        """Files we installed before that have been edited since, which this install would overwrite."""
        out = []
        for path, data in self.writes.items():
            rel = path.relative_to(self.base).as_posix()
            if rel in MERGED or not path.exists():
                continue
            current = _sha(path.read_bytes())
            if current == _sha(data):
                continue
            if rel not in self.manifest or self.manifest[rel] != current:
                out.append(rel)
        return out

    def apply(self) -> dict:
        conflicts = [] if self.force else self.conflicts()
        if conflicts:
            return {"installed": False, "refused": conflicts,
                    "note": "these files were changed by hand since they were installed (or are not ours); "
                            "move your changes into the repository's skills, or rerun with --force"}
        written = []
        for path, data in sorted(self.writes.items()):
            if path.exists() and path.read_bytes() == data:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_name(path.name + ".ros-tmp")
            tmp.write_bytes(data)
            tmp.replace(path)
            written.append(path.relative_to(self.base).as_posix())
        files = {**self.manifest, **{p.relative_to(self.base).as_posix(): _sha(d) for p, d in self.writes.items()
                                     if p.relative_to(self.base).as_posix() not in MERGED}}
        (self.base / MANIFEST).write_text(json.dumps({"repo": str(REPO), "files": files}, indent=2, sort_keys=True)
                                          + "\n", encoding="utf-8")
        return {"installed": True, "written": written, "unchanged": len(self.writes) - len(written)}


MERGED = {".claude/settings.json", ".mcp.json", ".gemini/settings.json", ".gemini/GEMINI.md", ".codex/config.toml", ".codex/AGENTS.md",
          "AGENTS.md", "GEMINI.md"}


def brief_hook_command() -> str:
    """What a SessionStart hook runs: ``ros brief --text`` from this repository, so the agent starts a session knowing
    what needs the researcher and what to do next. Quoted for sh and cmd alike."""
    code = f"import sys; sys.path.insert(0, r'{REPO}'); from ros.cli import main; main(['brief', '--text'])"
    return f'"{Path(sys.executable)}" -c "{code}"'


def _merge_hooks(old: str) -> str:
    """Add the briefing to ``hooks.SessionStart`` without touching any other hook or setting."""
    data = json.loads(old) if old.strip() else {}
    groups = data.setdefault("hooks", {}).setdefault("SessionStart", [])
    cmd = brief_hook_command()
    for g in groups:
        for h in g.get("hooks", []):
            if "from ros.cli import main; main(['brief', '--text'])" in h.get("command", ""):
                h["command"] = cmd  # ours: keep it pointing at this install
                return json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    groups.append({"hooks": [{"type": "command", "command": cmd}]})
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def install(client: str, base: Path | None = None, user: bool = False, force: bool = False,
            dry_run: bool = False, hooks: bool = False) -> dict:
    if client not in CLIENTS:
        raise ValueError(f"client is one of {', '.join(CLIENTS)}")
    base = (Path.home() if user else Path(base or Path.cwd())).resolve()
    plan = Plan(base, force)
    if client == "claude":
        for rel, data in skill_files().items():
            plan.file(f".claude/skills/{rel}", data)
        for name, data in agent_files().items():
            plan.file(f".claude/agents/{name}", data)
        if user:
            # forward slashes survive every shell (bash eats backslashes, PowerShell mangles "--")
            note = ("claude mcp add --scope user research-os -e PYTHONPATH=" + REPO.as_posix() + " -- "
                    + Path(sys.executable).as_posix() + " -m ros mcp")
        else:
            plan.merged(".mcp.json", lambda old: _merge_json(old, ["mcpServers", "research-os"], server_entry()))
            note = "MCP server registered in .mcp.json"
        if hooks:
            plan.merged(".claude/settings.json", _merge_hooks)
            note += "; a SessionStart hook runs `ros brief --text` in .claude/settings.json"
    elif client == "codex":
        for rel, data in skill_files().items():
            plan.file(f".agents/skills/{rel}", data)  # Codex's skills folder, in a project and in ~
        # a project reads AGENTS.md at its root; the user's global file is ~/.codex/AGENTS.md
        plan.merged(".codex/AGENTS.md" if user else "AGENTS.md", lambda old: _merge_block(old, instructions()))
        plan.merged(".codex/config.toml", lambda old: _merge_toml(old))
        note = "MCP server registered in .codex/config.toml" + ("" if user else " (project config; Codex reads "
                                                                 "~/.codex/config.toml unless the project is trusted)")
    elif client == "gemini":
        plan.merged(".gemini/GEMINI.md" if user else "GEMINI.md", lambda old: _merge_block(old, instructions()))
        plan.merged(".gemini/settings.json", lambda old: _merge_json(old, ["mcpServers", "research-os"], server_entry()))
        note = "MCP server registered in .gemini/settings.json"
    else:
        plan.merged("AGENTS.md", lambda old: _merge_block(old, instructions()))
        note = "AGENTS.md describes the ros tools; agents with MCP can add the server: " + json.dumps(server_entry())
    if dry_run:
        return {"dry_run": True, "base": str(base), "would_write": sorted(p.relative_to(base).as_posix()
                                                                           for p in plan.writes),
                "refused": plan.conflicts(), "note": note}
    if hooks and client != "claude":
        raise ValueError("hooks are a Claude Code feature: use --client claude")
    out = plan.apply()
    out.update(base=str(base), client=client)
    out.setdefault("note", note)  # a refusal keeps its own note: which files, and what to do
    return out


def _merge_json(old: str, keys: list[str], value) -> str:
    data = json.loads(old) if old.strip() else {}
    node = data
    for k in keys[:-1]:
        node = node.setdefault(k, {})
    node[keys[-1]] = value
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"  # the user's own non-ASCII text stays as written


def _merge_block(old: str, block: str) -> str:
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pattern.search(old):
        return pattern.sub(lambda m: block, old)
    return (old.rstrip() + "\n\n" if old.strip() else "") + block + "\n"


def _merge_toml(old: str) -> str:
    e = server_entry()
    block = "\n".join([TOML_BEGIN, "[mcp_servers.research-os]", f"command = {json.dumps(e['command'])}",
                       f"args = {json.dumps(e['args'])}", f"env = {{ PYTHONPATH = {json.dumps(e['env']['PYTHONPATH'])} }}",
                       TOML_END])
    pattern = re.compile(re.escape(TOML_BEGIN) + r".*?" + re.escape(TOML_END), re.S)
    if pattern.search(old):
        return pattern.sub(lambda m: block, old)
    return (old.rstrip() + "\n\n" if old.strip() else "") + block + "\n"


def _front(path: Path) -> dict:
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    out = {}
    for line in (m.group(1).splitlines() if m else []):
        k, _, v = line.partition(":")
        out[k.strip()] = v.strip()
    return out


def _load_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()
